def _word_wrap(text: str, max_chars_per_line: int = 24) -> list[str]:
    """Break text into word-wrapped lines."""
    words = text.split()
    lines: list[str] = []
    current: list[str] = []
    current_len = 0

    for word in words:
        if current_len + len(word) + (1 if current else 0) <= max_chars_per_line:
            current.append(word)
            current_len += len(word) + (1 if len(current) > 1 else 0)
        else:
            if current:
                lines.append(" ".join(current))
            current = [word]
            current_len = len(word)
    if current:
        lines.append(" ".join(current))
    return lines[:3]  # Max 3 lines


def create_hook_banner_bmp(
    text: str,
    output_path: Path | str,
    width: int = 960,
    height: int = 200,
    scale: int = 4,
) -> Path:
    """Generate a 32-bit BGRA transparent BMP with translucent pill and text."""
    out_file = Path(output_path)
    out_file.parent.mkdir(parents=True, exist_ok=True)

    lines = _word_wrap(text, max_chars_per_line=width // (scale * 9))
    if not lines:
        lines = ["HIGHLIGHT"]

    # Initialize 2D pixel buffer (y, x) -> [B, G, R, A]
    pixels = [[[0, 0, 0, 0] for _ in range(width)] for _ in range(height)]

    # Draw rounded pill background (translucent dark gray/black)
    pad_x, pad_y = 20, 16
    pill_w = width - (pad_x * 2)
    pill_h = height - (pad_y * 2)

    bg_b, bg_g, bg_r, bg_a = 15, 15, 20, 215  # Dark translucent
    for y in range(pad_y, pad_y + pill_h):
        for x in range(pad_x, pad_x + pill_w):
            pixels[y][x] = [bg_b, bg_g, bg_r, bg_a]

    # Calculate text rendering start
    char_w = 8 * scale
    char_h = 8 * scale
    line_spacing = 6
    total_text_h = len(lines) * char_h + (len(lines) - 1) * line_spacing
    start_y = max(pad_y + 8, (height - total_text_h) // 2)

    # Render each line with drop-shadow
    for line_idx, line in enumerate(lines):
        line_w = len(line) * char_w
        start_x = max(pad_x + 10, (width - line_w) // 2)
        curr_y = start_y + line_idx * (char_h + line_spacing)

        for char_idx, char in enumerate(line):
            ascii_code = ord(char)
            bitmap = _FONT_8X8.get(ascii_code, _FONT_8X8[32])
            char_x = start_x + char_idx * char_w

            # 1. Render Drop Shadow (offset +2, +2, black)
            _draw_glyph(pixels, bitmap, char_x + 2, curr_y + 2, scale, width, height, [0, 0, 0, 255])
            # 2. Render Main Glyph (bright white)
            _draw_glyph(pixels, bitmap, char_x, curr_y, scale, width, height, [255, 255, 255, 255])

    # Serialize to 32-bit BMP (bottom-to-top order)
    pixel_data = bytearray()
    for y in range(height):  # BMP rows are stored bottom-up
        row_y = y
        for x in range(width):
            pixel_data.extend(pixels[row_y][x])

    file_size = 54 + len(pixel_data)
    bmp_header = struct.pack("<2sIHHI", b"BM", file_size, 0, 0, 54)
    dib_header = struct.pack(
        "<IIIHHIIIIII",
        40,          # DIB Header size
        width,
        height,
        1,           # Color planes
        32,          # Bits per pixel (BGRA)
        0,           # BI_RGB uncompressed
        len(pixel_data),
        2835,        # 72 DPI
        2835,
        0,
        0,
    )

    with open(out_file, "wb") as fh:
        fh.write(bmp_header)
        fh.write(dib_header)
        fh.write(pixel_data)

    return out_file


def _draw_glyph(
    pixels: list[list[list[int]]],
    bitmap: list[int],
    start_x: int,
    start_y: int,
    scale: int,
    width: int,
    height: int,
    color: list[int],
) -> None:
    """Blit an 8x8 glyph bitmap onto the pixel grid with scaling."""
    for row in range(8):
        byte_val = bitmap[row]
        for col in range(8):
            if (byte_val >> (7 - col)) & 1:
                # Pixel is on
                for sy in range(scale):
                    for sx in range(scale):
                        px = start_x + col * scale + sx
                        py = start_y + (7 - row) * scale + sy  # Flip for bottom-up BMP
                        if 0 <= px < width and 0 <= py < height:
                            pixels[py][px] = list(color)
